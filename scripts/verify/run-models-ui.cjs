  if (!file.startsWith(verifyDir + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) { response.writeHead(404); return response.end(); }
  const type = file.endsWith('.html') ? 'text/html' : file.endsWith('.css') ? 'text/css' : file.endsWith('.woff2') ? 'font/woff2' : 'text/javascript';
  response.writeHead(200, { 'Content-Type': type }); fs.createReadStream(file).pipe(response);
