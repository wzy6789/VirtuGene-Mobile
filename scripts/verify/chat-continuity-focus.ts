import './chat-continuity-resume';
import {db} from '../../src/db';
import {messageRepo} from '../../src/db/message-repo';
import {memorySourceTombstoneRepo} from '../../src/db/memory-source-tombstone-repo';
import {collectBackupData} from '../../src/lib/backup';
import {encryptBackup,decryptBackup} from '../../src/lib/backup-crypto';
import {importSyncData} from '../../src/lib/sync';
const api=window as any,sessionId='resume-new-session',threadId='resume-original-thread';
const current=async()=>(await db.sessions.get(sessionId))?.conversation;
const prompt=(turn:any)=>turn.calls.find((call:any)=>call.body.messages[call.body.messages.length-1]?.content===turn.result.source.content)?.body.messages[0].content??'';
const hasFields=(text:string)=>{const block=text.match(/\[本轮接续事项\][\s\S]*?\[\/本轮接续事项\]/u)?.[0]??'';return block.includes('2030年1月7日14点')&&block.includes('地铁');};
const focused=async()=>{await api.prepareResumeReload();const first=await api.resumeAfterReload();return {first,anchor:first.result.source};};
api.runContinuityFocus=async()=>{
 const checks:Array<{name:string;ok:boolean}>=[],rows:any[]=[];
 const check=(name:string,ok:unknown)=>checks.push({name,ok:!!ok});
 let fixture=await focused(),state=await current();
 check('named resume persists exact focus and its local user source',!!state?.continuityFocus&&state.continuityFocus.threadId===threadId&&state.continuityFocus.source.messageId===fixture.anchor.id);
 let next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('vague follow-up uses original focused item before model request',!next.result.error&&!next.result.failed&&hasFields(prompt(next)));
 check('follow-up never changes the actual item or creates another one',(await db.continuityThreads.count())===1&&(await db.continuityThreads.get(threadId))?.status==='open');
 rows.push({scenario:'named-then-followup',fixture,next});
 fixture=await focused();
 const shifted=await api.resumeTestTurn('换个话题，聊聊小猫。');
 check('topic shift pauses the pointer and omits old item context',shifted.conversation?.continuityFocus?.paused===true&&!prompt(shifted).includes('[本轮接续事项]'));
 const paused=await api.resumeTestTurn('那原来几点，怎么去？');
 check('unqualified field question does not auto-resume paused focus',paused.conversation?.continuityFocus?.paused===true&&!prompt(paused).includes('[本轮接续事项]'));
 const reported=await api.resumeTestTurn('朋友说，继续刚才那个安排。');
 check('reported continuation cannot reactivate paused attention',reported.conversation?.continuityFocus?.paused===true&&!hasFields(prompt(reported)));
 const restored=await api.resumeTestTurn('继续刚才那个，几点出发？');
 check('explicit anaphoric continuation restores exact attention and fields',!restored.result.error&&!restored.result.failed&&restored.conversation?.continuityFocus?.paused!==true&&hasFields(prompt(restored)));
 check('resumed attention has the new current user activation evidence',restored.conversation?.continuityFocus?.activationSource?.messageId===restored.result.source.id);
 rows.push({scenario:'shift-pause-resume',shifted,paused,restored});
 await messageRepo.deleteById(restored.result.source.id);next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('deleted activation cannot remain an active focus',!next.conversation?.continuityFocus&&!prompt(next).includes('[本轮接续事项]'));
 fixture=await focused();await messageRepo.deleteById(fixture.anchor.id);next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('deleted initial focus control is not reused',!next.conversation?.continuityFocus&&!prompt(next).includes('[本轮接续事项]'));
 fixture=await focused();await messageRepo.update(fixture.anchor.id,{content:'原指令已改为普通闲聊。'});next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('edited initial focus control is not silently recertified',!next.conversation?.continuityFocus&&!prompt(next).includes('[本轮接续事项]'));
 fixture=await focused();const original=(await db.continuityThreads.get(threadId))!;
 await db.continuityThreads.put({...original,id:'focus-foreign',characterId:'another-role',userId:'another-owner',detail:'FOREIGN_FOCUS_SENTINEL'});
 const stored=(await current())!;
 await db.sessions.update(sessionId,{conversation:{...stored,continuityFocus:{threadId:'focus-foreign',source:{messageId:fixture.anchor.id,revision:1,start:0,end:fixture.anchor.content.length},domain:'user-reality'}} as any});
 next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('an imported pointer cannot follow another account or role',!prompt(next).includes('FOREIGN_FOCUS_SENTINEL')&&!next.result.replies.some((reply:any)=>reply.content.includes('FOREIGN_FOCUS_SENTINEL')));
 fixture=await focused();
 api.setResumeTestMutation(()=>db.continuityThreads.update(threadId,{detail:'另一窗口改过的事项。',updatedAt:Date.now()+1000}).then(()=>undefined));
 next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('later edits reject a focus-based stale reply',(next.result.failed||!!next.result.error)&&next.result.replies.length===0&&(await db.continuityThreads.get(threadId))?.detail==='另一窗口改过的事项。');
 rows.push({scenario:'late-focused-edit',next});
 fixture=await focused();const beforeWithdrawal=(await db.continuityThreads.get(threadId))!;
 await memorySourceTombstoneRepo.record({userId:'resume-owner',characterId:'resume-actor',sourceType:'continuityThread',sourceId:threadId,sourceRevision:beforeWithdrawal.updatedAt,status:'withdrawn'});
 next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('withdrawn item authority invalidates focus without a body change',!next.conversation?.continuityFocus&&!hasFields(prompt(next)));
 rows.push({scenario:'pre-focus-withdrawal',next});
 fixture=await focused();
 api.setResumeTestMutation(async()=>{const thread=(await db.continuityThreads.get(threadId))!;await memorySourceTombstoneRepo.record({userId:'resume-owner',characterId:'resume-actor',sourceType:'continuityThread',sourceId:threadId,sourceRevision:thread.updatedAt,status:'withdrawn'});});
 next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('withdrawal during the provider wait stops stale focused publication',(next.result.failed||!!next.result.error)&&next.result.replies.length===0);
 rows.push({scenario:'late-focus-withdrawal',next});
 fixture=await focused();await api.resumeTestTurn('晚上我不喝咖啡。');
 const withPreference=await api.resumeTestTurn('继续刚才那个安排，几点出发？');
 await messageRepo.deleteById(withPreference.result.source.id);next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('invalid focus evidence does not discard independently valid user preferences',!next.conversation?.continuityFocus&&next.conversation?.topics?.some((topic:any)=>topic.kind==='preference'&&topic.slots.object?.value==='咖啡'&&topic.slots.period?.value==='晚上'&&topic.slots.stance?.value==='不喝'));
 rows.push({scenario:'invalid-focus-valid-preference',next});
 fixture=await focused();
 await api.resumeTestTurn('陪我演一下，我们扮演小林的故事。');
 const inStory=await api.resumeTestTurn('那原来几点，怎么去？');
 await api.resumeTestTurn('退出扮演，我还是阿远。');
 const backToReality=await api.resumeTestTurn('继续刚才那个安排，几点出发？');
 check('story mode pauses real-item focus and explicit return rechecks it',inStory.conversation?.continuityFocus?.paused===true&&!hasFields(prompt(inStory))&&!backToReality.result.error&&hasFields(prompt(backToReality)));
 fixture=await focused();await api.resumeTestTurn('换个话题，聊聊小猫。');
 const activated=await api.resumeTestTurn('继续刚才那个安排，几点出发？');
 const backup=await collectBackupData('resume-owner','合成焦点验收');
 const encrypted=await encryptBackup(JSON.stringify(backup),'synthetic-focus-backup-only');
 const decoded=JSON.parse(await decryptBackup(encrypted,'synthetic-focus-backup-only'));
 await db.delete();await db.open();
 const imported=await importSyncData({...decoded,__meta__:{...decoded.__meta__,kind:'sync'}});
 await api.loadResumeTestSession();next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('actual encrypted backup/import retains exact locator and both user sources',imported.ok&&!next.result.error&&hasFields(prompt(next))&&next.conversation?.continuityFocus?.source.messageId===fixture.anchor.id&&next.conversation?.continuityFocus?.activationSource?.messageId===activated.result.source.id);
 await messageRepo.deleteById(activated.result.source.id);
 const replay=await importSyncData({...decoded,__meta__:{...decoded.__meta__,kind:'sync'}});
 await api.loadResumeTestSession();next=await api.resumeTestTurn('那原来几点，怎么去？');
 check('old backup cannot reinstate deleted activation authority',replay.ok&&!next.conversation?.continuityFocus&&!hasFields(prompt(next)));
 rows.push({scenario:'focus-backup-activation-replay',next});
 return {complete:checks.every(check=>check.ok),character:'古月娜',checks,failures:checks.filter(check=>!check.ok),rows,apiCalls:0};
};
api.prepareFocusReload=focused;
api.focusAfterReload=async()=>{await api.loadResumeTestSession();return api.resumeTestTurn('那原来几点，怎么去？');};
